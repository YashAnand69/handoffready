#!/usr/bin/env python3
"""Exercise the real loopback API and parser using an isolated synthetic packet.

No injected model is used. --with-model additionally runs the configured real
adapter and records completed/failed/unavailable inference explicitly. Scripted
fixture approvals are test actions, never evidence of human/customer review.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
import socket
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import httpx
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PRIVATE_BRIEF = "PRIVATE_BRIEF_SENTINEL_7b6ac0"
PRIVATE_NOTE = "PRIVATE_REVIEW_NOTE_SENTINEL_4c9a25"


def png(transparent):
    buffer = io.BytesIO()
    Image.new("RGBA", (8, 8), (35, 61, 51, 0 if transparent else 255)).save(buffer, format="PNG")
    return buffer.getvalue()


class Service:
    def __init__(self, directory):
        self.directory = directory
        with socket.socket() as socket_handle:
            socket_handle.bind(("127.0.0.1", 0))
            self.port = socket_handle.getsockname()[1]
        self.url = f"http://127.0.0.1:{self.port}"
        self.process = None
        self.client = httpx.Client(base_url=self.url, trust_env=False, timeout=140)
        self.log = (Path(directory) / "service.log").open("wb")

    def start(self):
        command = "import sys,uvicorn; from handoffready.api import create_app; uvicorn.run(create_app(data_dir=sys.argv[1],port=int(sys.argv[2])),host='127.0.0.1',port=int(sys.argv[2]),log_level='warning')"
        self.process = subprocess.Popen([sys.executable, "-c", command, str(self.directory), str(self.port)],
                                        cwd=ROOT, env={**os.environ, "PYTHONPATH": str(ROOT / "backend")}, stdout=self.log, stderr=subprocess.STDOUT)
        deadline = time.monotonic() + 15
        while time.monotonic() < deadline:
            if self.process.poll() is not None:
                raise RuntimeError("Isolated API exited before becoming ready.")
            try:
                result = self.client.get("/api/v1/bootstrap")
                if result.status_code == 200:
                    self.client.headers.update({"X-Handoff-Token": result.json()["data"]["token"], "Origin": self.url})
                    return
            except httpx.ConnectError:
                pass
            time.sleep(.1)
        raise RuntimeError("Isolated API did not become ready in 15 seconds.")

    def stop(self):
        if self.process is not None and self.process.poll() is None:
            self.process.terminate()
            try:
                self.process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=5)
        self.process = None

    def close(self):
        self.stop()
        self.client.close()
        self.log.close()

    def call(self, method, path, *, project=None, payload=None, expected=(200,), **kwargs):
        headers = {"If-Match": str(project["revision"])} if project else {}
        result = self.client.request(method, "/api/v1" + path, headers=headers, json=payload, **kwargs)
        if result.status_code not in expected:
            code = result.json().get("error", {}).get("code", "unexpected_response")
            raise RuntimeError(f"{method} {path}: HTTP {result.status_code}, {code}")
        return result.json()["data"]

    def project(self, project):
        return self.call("GET", f'/projects/{project["id"]}')

    def mutation(self, method, project, suffix, payload=None, expected=(200,)):
        return self.call(method, f'/projects/{project["id"]}' + suffix, project=project, payload=payload, expected=expected)


def wait_job(service, project, job_id):
    deadline = time.monotonic() + 130
    while time.monotonic() < deadline:
        value = service.call("GET", f'/projects/{project["id"]}/jobs/{job_id}')
        if value["state"] not in {"queued", "running"}:
            return {key: value.get(key) for key in ("id", "kind", "state", "stage", "error", "error_code", "model")}
        time.sleep(.2)
    raise RuntimeError("Job did not reach a terminal state within its advertised budget.")


def run(service, with_model):
    receipt = {"kind": "real-loopback-api-synthetic-workflow", "created_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
               "input_origin": "New synthetic images and brief generated by this verification script. No client data.",
               "approval_actor": "Scripted fixture verification; not human or customer approval.",
               "model_injection": False, "inference_requested": with_model, "steps": []}
    project = service.call("POST", "/projects", payload={"name": "Synthetic workflow verification"}, expected=(201,))
    brief = "Provide one transparent PNG logo at 8 by 8 pixels.\n" + PRIVATE_BRIEF
    project = service.mutation("PUT", project, "/brief", {"text": brief, "source_label": "Synthetic private brief"})
    receipt["steps"].append({"step": "source_saved", "canonical_source_sha256": project["brief"]["sha256"]})
    requirements = [{"id": "logo", "title": "Transparent PNG logo", "origin": "human_added", "quote": None, "source_id": None,
                     "human_note": "Manually entered synthetic verification requirement; this is not a customer approval.",
                     "checks": [{"kind": "presence", "types": ["png"]}, {"kind": "image_dimensions", "width_px": 8, "height_px": 8}, {"kind": "png_nonopaque_pixels"}]}]
    project = service.mutation("PUT", project, "/baseline", {"requirements": requirements})
    project = service.mutation("POST", project, "/baseline/approve", {"baseline_hash": project["baseline"]["hash"], "reviewed_requirement_ids": ["logo"]})
    receipt["steps"].append({"step": "typed_checklist_approved_by_test_script", "baseline_hash": project["baseline"]["hash"]})
    opaque, transparent = png(False), png(True)
    project = service.call("POST", f'/projects/{project["id"]}/files', project=project, expected=(201,), files={"files[]": ("logo.png", opaque, "image/png")})
    assert project["files"][0]["inspection"] == "inspected"
    assert project["files"][0]["metadata"]["nonopaque_pixels"] is False

    def confirm(current, disposition):
        return service.mutation("PUT", current, "/decisions/logo", {"file_ids": [current["files"][0]["id"]], "review_state": "confirmed", "human_disposition": disposition,
                                                                "internal_decision_note": PRIVATE_NOTE, "client_usage_note": "Use the supplied PNG logo.", "input_hash": current["input_hash"]})
    project = confirm(project, "needs_work")
    assert next(c for c in project["checks"] if c["kind"] == "png_nonopaque_pixels")["status"] == "fail"
    receipt["steps"].append({"step": "opaque_png_failure", "original_sha256": hashlib.sha256(opaque).hexdigest(), "checks": project["checks"]})
    denied = service.client.post(f'/api/v1/projects/{project["id"]}/exports', headers={"If-Match": str(project["revision"])}, json={"acknowledge_unresolved": False, "input_hash": project["input_hash"]})
    assert denied.status_code == 409
    preview = service.call("GET", f'/projects/{project["id"]}/handoff-preview')
    exported = service.mutation("POST", project, "/exports", {"acknowledge_unresolved": True, "input_hash": project["input_hash"]}, expected=(201,))
    first_export = exported["export"]
    assert first_export["status"] == "draft_with_gaps"
    preview_rows = preview["requirements"]
    assert preview_rows == first_export["preview"]["requirements"]
    project = service.project(project)
    original_exports = {}
    for format in ("json", "md", "html"):
        result = service.client.get(f'/api/v1/projects/{project["id"]}/exports/{first_export["id"]}/{format}')
        assert result.status_code == 200
        assert PRIVATE_NOTE not in result.text and PRIVATE_BRIEF not in result.text
        assert "Provide one transparent PNG logo at 8 by 8 pixels." not in result.text
        assert "Use the supplied PNG logo." in result.text
        original_exports[format] = result.content
    receipt["steps"].append({"step": "immutable_draft_exports", "id": first_export["id"], "private_sentinels_absent_in": ["json", "md", "html"],
                             "gaps": first_export["gaps"], "file_sha256": {key: hashlib.sha256(value).hexdigest() for key, value in original_exports.items()}})
    old_hash, old_file = project["input_hash"], project["files"][0]["id"]
    project = service.call("POST", f'/projects/{project["id"]}/files/{old_file}/replacement', project=project, expected=(201,), files={"file": ("logo.png", transparent, "image/png")})
    assert project["input_hash"] != old_hash
    assert project["decisions"][0]["review_state"] == "stale"
    assert all(c["status"] == "unknown" for c in project["checks"])
    receipt["steps"].append({"step": "replacement_invalidated_decision", "new_sha256": hashlib.sha256(transparent).hexdigest(), "review_state": "stale"})
    project = confirm(project, "satisfied")
    assert all(c["status"] == "pass" for c in project["checks"])
    corrected = service.mutation("POST", project, "/exports", {"acknowledge_unresolved": False, "input_hash": project["input_hash"]}, expected=(201,))
    assert corrected["export"]["status"] == "reviewed"
    receipt["steps"].append({"step": "reconfirmed_corrected_png", "checks": project["checks"], "export_status": corrected["export"]["status"]})

    readiness = service.call("GET", "/capabilities")["model"]
    receipt["model"] = {"readiness": readiness, "runs": [], "inference_attempted": False, "successful_inference_recorded": False, "inference_performed": False}
    if with_model and readiness.get("available"):
        model_project = service.call("POST", "/projects", payload={"name": "Synthetic actual inference verification"}, expected=(201,))
        model_project = service.mutation("PUT", model_project, "/brief", {"text": "Deliver one transparent PNG logo. Include written instructions for changing contact details."})
        started = service.mutation("POST", model_project, "/jobs/extract", {}, expected=(202,))
        receipt["model"]["inference_attempted"] = True
        extraction = wait_job(service, model_project, started["job"]["id"])
        receipt["model"]["runs"].append(extraction)
        # A request can fail before inference; provenance proves actual model completion.
        receipt["model"]["inference_performed"] = extraction["state"] == "succeeded"
        started = service.mutation("POST", project := service.project(project), "/jobs/match", {}, expected=(202,))
        matching = wait_job(service, project, started["job"]["id"])
        receipt["model"]["runs"].append(matching)
        receipt["model"]["published_proposals"] = service.project(project)["proposals"]
        receipt["model"]["inference_performed"] |= matching["state"] == "succeeded"
        receipt["model"]["successful_inference_recorded"] = receipt["model"]["inference_performed"]
        if not receipt["model"]["inference_performed"]:
            receipt["model"]["inference_performed"] = None  # A failed request may have executed inference without publishing valid output.
    elif with_model:
        receipt["model"]["not_run_reason"] = "Configured local model is unavailable. No inference or synthetic substitution was performed."
    else:
        receipt["model"]["not_run_reason"] = "Manual/parser workflow requested; no inference job was started."

    before_restart = service.project(project)
    service.stop()
    service.start()
    after_restart = service.project(project)
    assert after_restart["input_hash"] == before_restart["input_hash"]
    assert after_restart["decisions"] == before_restart["decisions"]
    assert len(after_restart["exports"]) == 2
    for format, original in original_exports.items():
        restored = service.client.get(f'/api/v1/projects/{project["id"]}/exports/{first_export["id"]}/{format}')
        assert restored.content == original
    receipt["steps"].append({"step": "restart_preserved_decisions_and_immutable_exports", "revision": after_restart["revision"], "snapshot_count": 2})
    receipt["manual_workflow_state"] = "passed"
    if not with_model:
        receipt["model"]["state"] = "not_requested"
    elif not readiness.get("available"):
        receipt["model"]["state"] = "unavailable"
    else:
        states = [job["state"] for job in receipt["model"]["runs"]]
        receipt["model"]["state"] = "passed" if states and all(state == "succeeded" for state in states) else "partial" if "succeeded" in states else "failed"
    receipt["state"] = "passed" if not with_model else receipt["model"]["state"]
    receipt["limitations"] = ["Synthetic scripted workflow, not customer testing or human review.", "Passing narrow file checks does not establish visual quality or contractual acceptance.", "Manual workflow verification is independent of whether optional local inference succeeds.", "Temporary source data is deleted on script completion; only this non-client receipt is preserved."]
    return receipt


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--with-model", action="store_true")
    parser.add_argument("--output", default="docs/workflow-verification.json")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="handoffready-verification-") as directory:
        service = Service(directory)
        try:
            service.start()
            receipt = run(service, args.with_model)
        finally:
            service.close()
    path = ROOT / args.output
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(receipt, indent=2, ensure_ascii=False) + "\n")
    print(json.dumps({"state": receipt["state"], "manual_workflow_state": receipt["manual_workflow_state"], "model_state": receipt["model"]["state"], "steps": len(receipt["steps"]), "inference_performed": receipt["model"]["inference_performed"], "receipt": str(path)}))
    if receipt["state"] != "passed":
        raise SystemExit(1)


if __name__ == "__main__":
    main()
